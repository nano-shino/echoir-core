#!/usr/bin/env python3
"""Generates src/text/score_tables.inc, the space and drop tables behind normalize_for_score.

The tables come from Unicode general categories, so no code point is missed by hand:
  - space: Zs, Zl and Zp, plus U+0009..U+000D and U+0085 (collapsed to one space)
  - drop:  P*, S*, Cc and Cf, plus the variation selectors (removed, leaving no space)

Standard library only. The interpreter's unicodedata must be EXPECTED_UNICODE, so an old
Python can't silently change the output. Run it from anywhere:

    python3.14 -I tools/gen-score-tables.py           # write the table
    python3.14 -I tools/gen-score-tables.py --check   # exit 1 if stale
"""

import os
import sys
import unicodedata

EXPECTED_UNICODE = "16.0.0"
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "text",
                        "score_tables.inc")

# Invisible selectors that change how the previous character looks (emoji and text style).
VARIATION_SELECTORS = ((0xFE00, 0xFE0F), (0xE0100, 0xE01EF))


def in_variation_selectors(cp):
    return any(lo <= cp <= hi for lo, hi in VARIATION_SELECTORS)


def add(ranges, cp):
    if ranges and ranges[-1][1] == cp - 1:
        ranges[-1] = (ranges[-1][0], cp)
    else:
        ranges.append((cp, cp))


def build_tables():
    if unicodedata.unidata_version != EXPECTED_UNICODE:
        sys.exit(f"error: unicodedata is Unicode {unicodedata.unidata_version}, "
                 f"expected {EXPECTED_UNICODE}; run with a Python that has it "
                 f"(for example python3.14)")
    space = []
    dropped = []
    for cp in range(0x110000):
        cat = unicodedata.category(chr(cp))
        if cat in ("Zs", "Zl", "Zp") or 0x09 <= cp <= 0x0D or cp == 0x85:
            add(space, cp)
        elif cat[0] in "PS" or cat in ("Cc", "Cf") or in_variation_selectors(cp):
            add(dropped, cp)
    return space, dropped


def code_points(ranges):
    return sum(hi - lo + 1 for lo, hi in ranges)


def emit_table(name, ranges):
    lines = [f"constexpr char32_t {name}[][2] = {{"]
    row = []
    for lo, hi in ranges:
        row.append(f"{{0x{lo:04X}, 0x{hi:04X}}}")
        if len(row) == 4:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def render(space, dropped):
    return "\n".join([
        f"// Generated by tools/gen-score-tables.py from Unicode {EXPECTED_UNICODE}. Do not edit.",
        f"// kSpace: {code_points(space)} code points in {len(space)} ranges.",
        f"// kDropped: {code_points(dropped)} code points in {len(dropped)} ranges.",
        "// Ranges are inclusive, sorted and disjoint, so score.cpp can binary-search them.",
        "// clang-format off",
        "namespace echoir::text::score_tables {",
        "",
        emit_table("kSpace", space),
        "",
        emit_table("kDropped", dropped),
        "",
        "}  // namespace echoir::text::score_tables",
        "// clang-format on",
        "",
    ])


def main(argv):
    space, dropped = build_tables()
    text = render(space, dropped)
    if "--check" in argv:
        try:
            with open(OUT_PATH, "r", encoding="utf-8", newline="") as f:
                current = f.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print(f"stale: {os.path.normpath(OUT_PATH)} (rerun without --check)", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {os.path.normpath(OUT_PATH)}: kSpace {code_points(space)} code points, "
          f"kDropped {code_points(dropped)} code points")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
